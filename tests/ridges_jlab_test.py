"""Regression tests of the ridge analysis against jLab, the reference implementation.

The CloudDrift ridge analysis is a port of Jonathan Lilly's jLab, and the port has
diverged from it in ways that only showed up in figures. These tests pin the agreement
down: ``tests/fixtures/jlab_reference.npz`` holds inputs, jLab's output for them, and the
ellipse properties jLab reports for three ridges of GDP drifter 44000.

The fixture is regenerated by running ``tests/fixtures/make_ridge_inputs.py`` and then
``tests/fixtures/make_ridge_fixtures.m`` in MATLAB with jLab on the path; the .mat files
stay in the gitignored ``data/`` directory and only this compact archive is committed. The
wavelet transform in the archive is subsampled in time by ``transform_stride`` to keep it
small.

Known and understood differences, which the tolerances below encode:

* At the lowest frequencies the two transforms differ by a few parts in a thousand, from
  the treatment of the record edges. That is enough to move the endpoints of a
  low-frequency ridge by a few samples.
* CloudDrift finds one short ridge at the end of the record that jLab does not report.
* jLab's reported instantaneous frequency comes from the ridge itself, while
  ``eddy_properties`` derives it from the recovered ellipse. The two differ by the
  modulation bias, which jLab reports as ``chi``, and the difference is largest for the
  most strongly modulated ridges.

The drifter data underlying the eddy case is from NOAA's Global Drifter Program.
"""

import pathlib
import unittest

import numpy as np
from scipy import integrate

from clouddrift.eddies import eddy_properties
from clouddrift.ridges import ridge_analysis
from clouddrift.signal import modulated_ellipse_signal
from clouddrift.wavelet import morse_wavelet_transform

FIXTURE = pathlib.Path(__file__).parent / "fixtures" / "jlab_reference.npz"


def load_fixture():
    return np.load(FIXTURE)


def jlab_ridges(fixture):
    """jLab separates its ridges with NaN; return one (first, last, count) per ridge."""
    time_index = fixture["ridge_time_index"]
    breaks = np.flatnonzero(np.isnan(time_index))
    ridges, start = [], 0
    for stop in list(breaks) + [time_index.size]:
        if stop > start:
            segment = time_index[start:stop] - 1  # MATLAB indices are 1-based
            ridges.append((segment[0], segment[-1], segment.size))
        start = stop + 1
    return ridges


def our_ridges(fixture):
    x, y, fs = fixture["x"], fixture["y"], fixture["fs"]
    gamma, beta = float(fixture["ga"]), float(fixture["be"])
    minimum_length = float(fixture["M"]) * 2 * float(fixture["P"]) / np.pi
    time = np.arange(x.size, dtype=float)
    wx = morse_wavelet_transform(x.astype(float), gamma, beta, fs, boundary="mirror")
    wy = morse_wavelet_transform(y.astype(float), gamma, beta, fs, boundary="mirror")
    result = ridge_analysis((wx, wy), fs, time, min_ridge_size=int(np.ceil(minimum_length)))
    edges = np.concatenate([[0], np.cumsum(result["rowsize"].values)])
    ridges = []
    for k in range(result.sizes["ridge"]):
        if result["ridge_length"].values[k] <= minimum_length:
            continue
        span = slice(edges[k], edges[k + 1])
        ridge_time = result["time"].values[span]
        ridges.append((ridge_time[0], ridge_time[-1], ridge_time.size))
    return ridges


class wavelet_transform_against_jlab(unittest.TestCase):
    def test_transform_matches(self):
        """The wavelet transforms agree wherever the wavelet fits inside the record."""
        fixture = load_fixture()
        stride = int(fixture["transform_stride"])
        gamma, beta, P = float(fixture["ga"]), float(fixture["be"]), float(fixture["P"])
        fs = fixture["fs"]

        for component, reference in (
            ("x", fixture["transform_x"]),
            ("y", fixture["transform_y"]),
        ):
            ours = morse_wavelet_transform(
                fixture[component].astype(float), gamma, beta, fs, boundary="mirror"
            )[:, ::stride]
            n_times = ours.shape[1]
            for k, frequency in enumerate(fs):
                # skip frequencies whose wavelet cannot fit clear of both edges
                half_width = P / frequency / stride
                if 6 * half_width >= n_times:
                    continue
                interior = slice(int(3 * half_width), n_times - int(3 * half_width))
                mine, theirs = ours[k, interior], reference[k, interior]
                amplitude = np.abs(mine)
                strong = amplitude > 0.05 * amplitude.max()
                if strong.sum() < 10:
                    continue
                ratio = np.abs(theirs[strong]) / amplitude[strong]
                self.assertLess(
                    abs(np.median(ratio) - 1),
                    5e-3,
                    f"{component}, frequency index {k}: amplitude ratio {np.median(ratio)}",
                )


class ridge_analysis_against_jlab(unittest.TestCase):
    def test_same_ridges(self):
        """Every ridge jLab finds is found here, with the same extent and size."""
        fixture = load_fixture()
        theirs, mine = jlab_ridges(fixture), our_ridges(fixture)
        self.assertEqual(len(theirs), 4)

        for first, last, count in theirs:
            matches = [
                r
                for r in mine
                # endpoints within 20 samples: the low-frequency ridge starts a few
                # samples later here, from the difference in edge treatment
                if abs(r[0] - first) <= 20 and abs(r[1] - last) <= 20
            ]
            self.assertEqual(
                len(matches), 1, f"jLab ridge {first:.0f}-{last:.0f} has no counterpart"
            )
            self.assertLess(
                abs(matches[0][2] - count) / count,
                0.02,
                f"jLab ridge {first:.0f}-{last:.0f}: point counts differ by more than 2%",
            )

    def test_no_more_than_one_extra_ridge(self):
        """CloudDrift reports one short ridge at the end of the record that jLab does not.

        This is not asserted as correct, only pinned: if the count changes, the chaining or
        the length criterion has changed and the difference should be understood.
        """
        fixture = load_fixture()
        theirs, mine = jlab_ridges(fixture), our_ridges(fixture)
        extra = [
            r
            for r in mine
            if not any(abs(r[0] - a) <= 20 and abs(r[1] - b) <= 20 for a, b, _ in theirs)
        ]
        self.assertEqual(len(extra), 1)
        self.assertGreater(extra[0][0], 3500)  # in the last tenth of the record

    def test_ridge_length_criterion_follows_jlab(self):
        """The ridge length integrates the instantaneous frequency, Eq. (60).

        Integrating the scale frequency instead lets two marginal ridges through and gives
        six ridges where jLab reports four, which is how this was found.
        """
        fixture = load_fixture()
        x, y, fs = fixture["x"].astype(float), fixture["y"].astype(float), fixture["fs"]
        gamma, beta = float(fixture["ga"]), float(fixture["be"])
        minimum_length = float(fixture["M"]) * 2 * float(fixture["P"]) / np.pi
        time = np.arange(x.size, dtype=float)
        wx = morse_wavelet_transform(x, gamma, beta, fs, boundary="mirror")
        wy = morse_wavelet_transform(y, gamma, beta, fs, boundary="mirror")
        result = ridge_analysis((wx, wy), fs, time, min_ridge_size=2)

        edges = np.concatenate([[0], np.cumsum(result["rowsize"].values)])
        for k in range(result.sizes["ridge"]):
            span = slice(edges[k], edges[k + 1])
            ridge_time = result["time"].values[span]
            if ridge_time.size < 5:
                continue

            def integral(name, span=span, ridge_time=ridge_time):
                values = result[name].values[span]
                return np.abs(integrate.simpson(values, x=ridge_time)) / (2 * np.pi)

            from_instantaneous = integral("inst_frequency")
            from_scale = integral("frequency")
            self.assertAlmostEqual(result["ridge_length"].values[k], from_instantaneous, places=6)
            # and the two integrals are distinguishable, so the test is not vacuous
            if abs(from_scale - from_instantaneous) > 1e-3:
                self.assertGreater(abs(result["ridge_length"].values[k] - from_scale), 1e-4)

        kept = (result["ridge_length"].values > minimum_length).sum()
        self.assertEqual(kept, 5)  # jLab's four plus the extra one at the record end


class eddy_properties_against_jlab(unittest.TestCase):
    """The property layer, on the three longest ridges of GDP drifter 44000.

    The analytic signals are rebuilt from jLab's own ellipse parameters, so both sides
    describe the identical ellipse and only the derived quantities are compared.
    """

    def setUp(self):
        fixture = load_fixture()
        self.fixture = fixture
        self.spans = []
        edges = np.concatenate([[0], np.cumsum(fixture["eddy_rowsize"])])
        for k in range(fixture["eddy_rowsize"].size):
            self.spans.append(slice(int(edges[k]), int(edges[k + 1])))

    def properties(self, span):
        f = self.fixture
        circularity = f["eddy_xi"][span].astype(float)
        linearity = np.sign(circularity) * np.sqrt(np.clip(1 - circularity**2, 0, 1))
        xa, ya = modulated_ellipse_signal(
            f["eddy_kappa"][span].astype(float),
            linearity,
            f["eddy_theta"][span].astype(float),
            f["eddy_phi"][span].astype(float),
        )
        return eddy_properties(xa, ya, f["eddy_num"][span].astype(float))

    def test_radius_matches_exactly(self):
        """R = sqrt(a*b) is a pure function of the ellipse, so it should match to precision."""
        for span in self.spans:
            interior = slice(5, -5)
            ours = self.properties(span)["radius"].values[interior]
            theirs = self.fixture["eddy_R"][span][interior].astype(float)
            np.testing.assert_allclose(ours, theirs, rtol=1e-5)

    def test_velocity_matches(self):
        """V, the kinetic energy velocity, in cm/s from km/day."""
        km_per_day_to_cm_per_s = 1e5 / 86400
        for span in self.spans:
            interior = slice(5, -5)
            ours = self.properties(span)["velocity"].values[interior]
            theirs = self.fixture["eddy_V"][span][interior].astype(float)
            ratio = np.median(ours * km_per_day_to_cm_per_s / theirs)
            self.assertAlmostEqual(ratio, 1.0, delta=0.1)

    def test_frequency_matches_within_the_modulation_bias(self):
        """omega from the recovered ellipse against omega from the ridge.

        These are the same quantity in theory and differ in practice by the modulation
        bias that jLab reports as chi, so the tolerance is loose and the correlation with
        chi is the thing to watch if it degrades.
        """
        for span in self.spans:
            interior = slice(5, -5)
            ours = self.properties(span)["frequency"].values[interior]
            theirs = self.fixture["eddy_omega"][span][interior].astype(float)
            ratio = np.median(ours) / np.median(theirs)
            self.assertAlmostEqual(ratio, 1.0, delta=0.05)


if __name__ == "__main__":
    unittest.main()
